#!/usr/bin/env python3
"""Generates the data for the on-watch settings menu from resources/settings/settings.xml.

Settings strings have scope="settings", so they are not available to the watch face at
runtime. This script resolves the English labels and writes:
  resources/jsondata/menu_tN.json   one file per distinct option list: [[value, label], ...]
  resources/jsondata/menu.xml       the jsonData resource declarations
  source/SettingsMenuData.mc        the menu items: [property key, title, option list resource]

Identical option lists (e.g. the data field choices used by several settings) share one file.

Usage: python3 tools/gen_settings_menu.py   (run from the repository root after editing MENU)
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

# Settings shown in the on-watch menu, in menu order.
MENU = [
    "colorTheme", "nightColorTheme",
    "aboveClockLines", "weatherLine1Shows", "weatherLine2Shows", "dateFieldShows",
    "notificationCountShows", "showSeconds",
    "leftValueShows", "middleValueShows", "rightValueShows", "fourthValueShows",
    "bottomFieldShows",
    "leftBarShows", "rightBarShows",
    "sunriseFieldShows", "sunsetFieldShows",
    "aodFieldShows",
    "remindersEnabled", "remindWindowMin", "remindRepeatMin", "moveThreshold", "hrMargin",
]

root = Path(__file__).resolve().parent.parent
strings = {s.get("id"): (s.text or "").strip()
           for s in ET.parse(root / "resources/strings/strings.xml").getroot().iter("string")}


def resolve(text):
    # Example: "@Strings.settings_hidden" -> "Hidden"; plain text is returned unchanged.
    m = re.fullmatch(r"@Strings\.(\w+)", (text or "").strip())
    return strings[m.group(1)] if m else (text or "").strip()


settings = {}
for st in ET.parse(root / "resources/settings/settings.xml").getroot().iter("setting"):
    key = st.get("propertyKey", "").replace("@Properties.", "")
    cfg = st.find("settingConfig")
    entries = [[int(e.get("value")), resolve(e.text)] for e in st.iter("listEntry")]
    kind = "boolean" if cfg is not None and cfg.get("type") == "boolean" else "list"
    settings[key] = (resolve(st.get("title")).rstrip(":").strip(), entries, kind)

out = root / "resources/jsondata"
out.mkdir(exist_ok=True)
for old in out.glob("menu_t*.json"):
    old.unlink()

tables = {}  # json text -> resource id
items = []
for key in MENU:
    title, entries, kind = settings[key]
    if kind == "boolean":
        items.append((key, title, None))  # shown as an on/off toggle
        continue
    if not entries:
        raise SystemExit(f"{key} is neither a list nor a boolean setting")
    text = json.dumps(entries, ensure_ascii=False, separators=(",", ":"))
    if text not in tables:
        rid = f"menu_t{len(tables)}"
        tables[text] = rid
        (out / f"{rid}.json").write_text(text + "\n", encoding="utf-8")
    items.append((key, title, tables[text]))

decls = "\n".join(f'    <jsonData id="{rid}" filename="{rid}.json"/>' for rid in tables.values())
(out / "menu.xml").write_text(f"<!-- Generated by tools/gen_settings_menu.py -->\n<resources>\n{decls}\n</resources>\n",
                              encoding="utf-8")

rows = ",\n".join(f'            [{json.dumps(k)}, {json.dumps(t, ensure_ascii=False)}, '
                  f'{"null" if r is None else "Rez.JsonData." + r}]' for k, t, r in items)
(root / "source/SettingsMenuData.mc").write_text(f"""// Generated by tools/gen_settings_menu.py - edit MENU there and re-run instead of editing this file.
import Toybox.Lang;

module SettingsMenuData {{
    // [property key, title, option list resource, or null for an on/off setting]
    function items() as Array<Array> {{
        return [
{rows}
        ] as Array<Array>;
    }}
}}
""", encoding="utf-8")

print(f"{len(items)} settings, {len(tables)} option lists")
